    static func tr(_ key: String) -> String {
        switch Settings.language {
        case "zh-Hans": return zh[key] ?? key
        case "en": return en[key] ?? key
        default:
            let isZh = Locale.preferredLanguages.first?.hasPrefix("zh") ?? false
            return (isZh ? zh : en)[key] ?? key
        }
    }

    static func tr(_ key: String, _ arg: String) -> String {
        tr(key).replacingOccurrences(of: "%@", with: arg)
    }
